"""PromptCAD: a tiny, deterministic text-to-parametric-CAD learning project."""
from __future__ import annotations
import argparse
import re
from pathlib import Path


def dimension(text: str, name: str, default: float) -> float:
    match = re.search(rf"\b{ name }\s*(?:=|:|of)?\s*(\d+(?:\.\d+)?)\s*(?:mm)?\b", text, re.I)
    return float(match.group(1)) if match else default


def generate(prompt: str) -> str:
    """Map a small, documented prompt vocabulary to editable OpenSCAD."""
    p = prompt.lower()
    if not prompt.strip():
        raise ValueError("Prompt cannot be empty")
    if any(w in p for w in ("cylinder", "tube", "pipe", "ring")):
        radius = dimension(p, "radius", 10)
        height = dimension(p, "height", 20)
        wall = dimension(p, "wall", 2)
        if min(radius, height, wall) <= 0 or wall >= radius:
            raise ValueError("radius, height, and wall must be positive; wall must be less than radius")
        body = f"difference() {{\n    cylinder(h={height:g}, r={radius:g}, center=true, $fn=64);\n    cylinder(h={height+0.2:g}, r={radius-wall:g}, center=true, $fn=64);\n}}"
        kind = "hollow cylinder"
    elif any(w in p for w in ("sphere", "ball")):
        radius = dimension(p, "radius", 10)
        if radius <= 0: raise ValueError("radius must be positive")
        body = f"sphere(r={radius:g}, $fn=64);"
        kind = "sphere"
    else:
        x, y, z = (dimension(p, n, d) for n, d in (("width", 30), ("depth", 20), ("height", 10)))
        if min(x, y, z) <= 0: raise ValueError("width, depth, and height must be positive")
        body = f"cube([{x:g}, {y:g}, {z:g}], center=true);"
        kind = "box"
    return f"// Generated by PromptCAD from: {prompt.strip()}\n// Primitive-based parametric draft; inspect dimensions before use.\n$fn = 64;\n// Detected shape: {kind}\n{body}\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Turn a simple text prompt into editable OpenSCAD (.scad) geometry.")
    parser.add_argument("prompt", help='e.g. "box width 40 depth 20 height 8 mm"')
    parser.add_argument("-o", "--output", default="model.scad", help="output .scad path")
    args = parser.parse_args()
    try:
        output = Path(args.output)
        output.write_text(generate(args.prompt), encoding="utf-8")
        print(f"Wrote {output.resolve()}")
        print("Review the generated geometry in OpenSCAD; this prototype does not guarantee printability.")
    except (OSError, ValueError) as exc:
        parser.error(str(exc))

if __name__ == "__main__":
    main()
